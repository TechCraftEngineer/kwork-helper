import type { KworkProject, ProjectAnalysis, UserProfile } from "@repo/types";
import { generateText, Output } from "ai";
import { z } from "zod";
import { withModelFallback } from "./model-with-fallback";

const analysisSchema = z.object({
  isMatch: z.boolean().describe("Подходит ли проект для данного профиля"),
  reason: z.string().describe("Краткое объяснение решения (1-2 предложения)"),
  suggestedDuration: z
    .number()
    .int()
    .min(1)
    .describe(
      "Реалистичный срок выполнения в днях, исходя из сложности задачи (целое число от 1 до 30)",
    ),
  proposalText: z
    .string()
    .describe(
      "Текст отклика (без markdown, живой человеческий стиль, опыт + план решения единым текстом)",
    ),
});

const OPENING_VARIANTS = [
  "Добрый день.",
  "Здравствуйте.",
  "Добрый день!",
  "Здравствуйте!",
];

const CLOSING_VARIANTS = [
  "Готов обсудить детали.",
  "Напишите, если есть вопросы.",
  "Можем обсудить подробнее.",
  "Пишите, обсудим.",
  "Готов взяться за задачу.",
];

const NO_REVIEWS_TRUST_VARIANTS = [
  "Профиль на Кворке новый — работаю по вашему бюджету, мне важен первый отзыв.",
  "На платформе только начинаю, поэтому беру задачу по указанной цене — ради первого отзыва.",
  "Могу разбить оплату по этапам, чтобы проще было начать — профиль здесь свежий.",
  "Кворк для меня новая площадка, работаю строго по вашему бюджету ради первого отзыва.",
];

// Варианты подачи — как опыт и план переплетаются в тексте
const FLOW_VARIANTS = [
  "Упомяни 1-2 кейса из МОИ КЕЙСЫ своими словами. Потом естественным переходом — «здесь сделаю похожим образом» или «в этом проекте подойду так же» — переходи к плану: что именно сделаешь и какой ключевой момент важен.",
  "Начни с того, как именно подойдёшь к задаче — конкретный план в 1-2 предложениях. Потом органично добавь опыт: «делал похожее — [кейс из МОИ КЕЙСЫ своими словами]». Одного-двух кейсов достаточно.",
  "Опиши решение задачи: что сделаешь и в какой последовательности. По ходу, там где уместно, вплети кейс из МОИ КЕЙСЫ как доказательство — «такое уже строил: [кратко]». Опыт должен быть частью рассказа о решении, а не отдельным блоком.",
];

const ANALYSIS_SYSTEM_PROMPT = `
Ты — разработчик на фрилансе, который откликается на проект на Kwork.

ГОЛОС И СТИЛЬ:
- Пиши как пишешь коллеге-разработчику в мессенджере: коротко, по делу, без официоза.
- Никакого маркетингового языка. Никаких шаблонных фраз. Реальный человек — реальный стиль.
- Один абзац. 4–6 предложений. Каждое следующее должно логически продолжать предыдущее.
- Не начинай предложения с "Я". Меньше "я" — больше дела.
- Не пересказывай задачу клиента. Не объясняй очевидное.

ЧТО ДОЛЖНО БЫТЬ В ОТКЛИКЕ:
1. Опыт: один-два релевантных кейса из МОИ КЕЙСЫ, описанных своими словами — как факт, а не как реклама. "Делал похожее: [коротко]" — и сразу переходи к делу.
2. План: что сделаешь и почему именно так. Конкретно, без абстракций. Почему это важно знать клиенту — вот что пиши.

ЧТОБЫ КЛИЕНТ ЗАХОТЕЛ ВЫБРАТЬ ТЕБЯ:
- Покажи, что понимаешь суть задачи — не поверхностно, а видишь ключевой момент, на который стоит обратить внимание. Это главное.
- Не продавай — информируй. Клиент сам решает, ты только даёшь факты.
- Если видишь подводный камень или нюанс — напиши. Это выделяет.
- Будь уверен в том, что пишешь. Без "возможно", "вероятно", "может быть".

ЗАПРЕЩЕННЫЕ СЛОВА И ФРАЗЫ (не использовать ни в какой форме):
- Канцелярит: "в рамках", "осуществить", "реализовать", "качественно", "профессионально", "под ключ", "в кратчайшие сроки", "с удовольствием", "интересный проект", "рад приветствовать"
- Парафраз задачи: "Понял", "Понимаю задачу", "Вижу, что нужно", "Нужно сделать X, Y и Z", "Смотрю, требуется", "Ознакомился с задачей"
- Шаблонные заверения: "гарантирую", "обещаю"
- Продажный тон: "готов предложить", "предлагаю свои услуги", "выбрать меня"
- Лишние восклицания: более одного "!" на весь текст
- Перечисление стека: "интегрировал X, построил Y, плюс Z"

ЗАПРЕЩЕНО ВООБЩЕ:
- Выдумывать кейсы — только из раздела МОИ КЕЙСЫ. Если ни один не подходит — пиши только план, без кейсов.
- Упоминать технологии из своего стека, которых нет в задаче.
- Называть конкретные сроки (дни, часы, недели).
- Хвалить проект или заказчика.
- Писать отклик длиннее 6 предложений.

НОВЫЙ ПРОФИЛЬ (нет отзывов):
- Если NEW_PROFILE: true — вставь ОДНУ короткую фразу из NO_REVIEWS_TRUST дословно, в конце предложения, перед закрывающей фразой. Не выделяй в отдельный абзац, не выделяй курсивом.
- Фраза должна снижать риск для клиента: работаю по вашему бюджету за первый отзыв.
- Не пиши "у меня нет отзывов". Пиши "профиль новый" или "на платформе только начинаю".
- Если NEW_PROFILE не указан — тему отзывов не поднимай.

КРИТЕРИИ isMatch = false (не откликаться):
- Вёрстка (HTML/CSS, landing page, сверстать).
- WordPress (настройка, администрирование, шаблоны, плагины, WP).
- Парсинг Avito, Юла, Циан, Дзен и аналогичных сервисов.
- Требуются навыки не из твоего стека (нативная мобильная разработка, Unity, C++, PHP, Python и т.д.).
- Слишком мелкая задача (исправить одну кнопку, поменять цвет).
- Bitrix как основная задача (но Bitrix как платформа с интеграциями/автоматизацией — ок).

ПРИМЕР ХОРОШЕГО ОТКЛИКА (только как ориентир тона, не копируй):
"Добрый день! Делал реферальную систему для SaaS — приглашения, начисление бонусов, статистика. Здесь сначала спроектирую модель данных, чтобы логика начислений не превратилась в спагетти потом. Подключу уведомления и дашборд для отслеживания. Профиль на Кворке новый — беру по вашей цене за первый отзыв. Напишите, если есть вопросы."
`.trim();

function pickRandom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)] as T;
}

function buildCasesSection(profile: UserProfile): string {
  if (!profile.cases?.length) return "";
  const lines = profile.cases.map(
    (c, i) => `${i + 1}. ${c.description} [теги: ${c.tags.join(", ")}]`,
  );
  return `\nМОИ КЕЙСЫ (используй только их, не выдумывай новые):\n${lines.join("\n")}`;
}

export async function analyzeAndGenerateOffer(
  profile: UserProfile,
  project: KworkProject,
  noReviews = true,
): Promise<ProjectAnalysis> {
  const opening = pickRandom(OPENING_VARIANTS);
  const closing = pickRandom(CLOSING_VARIANTS);
  const flow = pickRandom(FLOW_VARIANTS);
  const trustPhrase = noReviews ? pickRandom(NO_REVIEWS_TRUST_VARIANTS) : null;

  const suggestedPrice = project.price;

  const casesSection = buildCasesSection(profile);

  const userPrompt = `
Проанализируй проект и реши, стоит ли откликаться.

МОЙ ПРОФИЛЬ:
- Имя: ${profile.name}
- Специализация: ${profile.specialization}
- Опыт: ${profile.experienceYears} лет
- О себе: ${profile.bio}
- Портфолио: ${profile.portfolioDescription}

МОЙ СТЕК (сгруппирован по доменам):
- Frontend: Next.js, React, TypeScript, Tailwind CSS
- Backend/API: Node.js, Bun.js, tRPC, Hono.js
- Базы данных: PostgreSQL, ClickHouse
- AI/LLM: Vercel AI SDK, ChatGPT, LLM-интеграция, OpenRouter
- Инфраструктура: Docker, k3s, Vercel
- Автоматизация: trigger.dev, Inngest
${casesSection}

ПРОЕКТ:
- Название: ${project.title}
- Описание: ${project.description}
- Бюджет: ${project.price} руб.${project.allow_higher_price ? ` (готов платить до ${project.possible_price_limit ?? project.price} руб.)` : ""}
- Откликов уже: ${project.offers}
- Процент найма: ${project.user_hired_percent}%
${trustPhrase ? `\nNEW_PROFILE: true\nNO_REVIEWS_TRUST: "${trustPhrase}"` : ""}

ЗАДАЧА:
1. isMatch — подходит ли проект под мой стек (см. критерии в системном промпте)
2. reason — кратко почему да/нет (1-2 предложения)
3. suggestedDuration — реалистичный срок выполнения в днях (целое число, от 1 до 30). Если не подходит — верни 1.
4. proposalText — если подходит: напиши отклик. Начни с "${opening}", заверши фразой "${closing}". Подача: ${flow} Если не подходит — верни пустую строку.
`.trim();

  const result = await withModelFallback((model, modelId) =>
    generateText({
      model,
      system: ANALYSIS_SYSTEM_PROMPT,
      prompt: userPrompt,
      output: Output.object({ schema: analysisSchema }),
      temperature: 0.8,
      experimental_telemetry: {
        isEnabled: true,
        functionId: "analyze-and-generate-offer",
        metadata: { modelId },
      },
    }),
  );

  return {
    ...result.output,
    suggestedPrice,
    suggestedDuration: result.output.suggestedDuration,
  };
}
