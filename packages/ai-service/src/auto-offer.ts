import type { KworkProject, ProjectAnalysis, UserProfile } from "@repo/types";
import { generateText, Output } from "ai";
import { z } from "zod";
import { withModelFallback } from "./model-with-fallback";

const analysisSchema = z.object({
  isMatch: z.boolean().describe("Подходит ли проект для данного профиля"),
  reason: z.string().describe("Краткое объяснение решения (1-2 предложения)"),
  suggestedDuration: z
    .number()
    .int()
    .min(1)
    .describe(
      "Реалистичный срок выполнения в днях, исходя из сложности задачи (целое число от 1 до 30)",
    ),
  proposalText: z
    .string()
    .describe(
      "Текст отклика (без markdown, живой человеческий стиль, опыт + план решения единым текстом)",
    ),
});

const OPENING_VARIANTS = [
  "Добрый день.",
  "Здравствуйте.",
  "Добрый день!",
  "Здравствуйте!",
];

const CLOSING_VARIANTS = [
  "Готов обсудить детали.",
  "Напишите, если есть вопросы.",
  "Можем обсудить подробнее.",
  "Пишите, обсудим.",
  "Готов взяться за задачу.",
];

const NO_REVIEWS_TRUST_VARIANTS = [
  "Профиль на Кворке новый — готов сделать первый проект чуть дешевле в обмен на честный отзыв.",
  "На платформе только начинаю, поэтому готов уступить по цене — мне важен первый отзыв.",
  "Могу разбить оплату по этапам, чтобы проще было начать — профиль здесь свежий.",
  "Кворк для меня новая площадка, поэтому готов гибко подойти к цене ради первого отзыва.",
];

// Варианты подачи — как опыт и план переплетаются в тексте
const FLOW_VARIANTS = [
  "Упомяни 1-2 кейса из МОИ КЕЙСЫ своими словами. Потом естественным переходом — «здесь сделаю похожим образом» или «в этом проекте подойду так же» — переходи к плану: что именно сделаешь и какой ключевой момент важен.",
  "Начни с того, как именно подойдёшь к задаче — конкретный план в 1-2 предложениях. Потом органично добавь опыт: «делал похожее — [кейс из МОИ КЕЙСЫ своими словами]». Одного-двух кейсов достаточно.",
  "Опиши решение задачи: что сделаешь и в какой последовательности. По ходу, там где уместно, вплети кейс из МОИ КЕЙСЫ как доказательство — «такое уже строил: [кратко]». Опыт должен быть частью рассказа о решении, а не отдельным блоком.",
];

const AUTO_OFFER_SYSTEM_PROMPT = `
Ты — живой фрилансер, пишешь отклик на проект с биржи Kwork.

ЦЕЛЬ: заказчик должен понять — ты уже делал похожее и знаешь как решить его задачу. Оба момента (опыт + план) должны присутствовать и читаться как единый связный текст, а не два отдельных параграфа.

ПРИМЕР ХОРОШЕГО ОТКЛИКА (только как иллюстрация стиля, не копируй):
"Добрый день! Строил реферальную систему для SaaS-продукта — приглашения, начисление бонусов, статистика в личном кабинете. Здесь сделаю то же самое: настрою логику начислений, подключу уведомления и сделаю дашборд для отслеживания. Ключевой момент — правильно спроектировать модель данных с самого начала, чтобы потом не переделывать. На Кворке профиль свежий — готов сделать чуть дешевле в обмен на честный отзыв. Готов обсудить детали."

ПРАВИЛА ТЕКСТА:
- 4-6 предложений. Не коротко и не длинно.
- Никакого markdown, никаких списков, никаких заголовков. Сплошной текст.
- Пиши как человек: живо, конкретно, без канцелярита.
- Опыт и план переплетены — не два отдельных блока, а единый рассказ.
- Не начинай каждое предложение с "Я".
- Не обещай "гарантии", не хвали проект.
- Никогда не называй конкретные сроки (дни, часы, недели).
- Запрещённые слова: "Привет", "Приветствую", "рад", "готов предложить", "данный", "осуществить", "реализовать", "в рамках", "в кратчайшие сроки", "качественно", "профессионально", "под ключ", "с удовольствием", "интересный проект".

РАБОТА С НОВЫМ ПРОФИЛЕМ (НЕТ ОТЗЫВОВ):
- Если в запросе указано NEW_PROFILE: true — вставь фразу о доверии ПЕРЕД финальной закрывающей фразой.
- Фраза должна снижать риск для клиента: предложи скидку за первый отзыв ИЛИ оплату по этапам.
- Одно короткое предложение — не отдельный блок, не отдельный абзац, просто часть текста.
- НЕ пиши "у меня нет отзывов" — пиши "профиль новый" или "только начинаю на платформе".
- Используй фразу из поля NO_REVIEWS_TRUST дословно — не перефразируй.
- Если NEW_PROFILE не указан или false — не упоминай отзывы вообще.

ЗАПРЕЩЕНО:
- Никогда не выдумывай кейсы — используй только те, что есть в разделе МОИ КЕЙСЫ.
- Если ни один кейс не подходит к задаче — не упоминай кейсы вообще, пиши только план решения.
- Никогда не пересказывай задачу клиента ("Понял, нужно...", "Нужно сделать X, Y и Z", "Вижу, требуется...").
- Никогда не перечисляй стек через запятую ("интегрировал X, построил Y, плюс Z").
- Не упоминай технологии из своего стека, которых нет в задаче.
- Не делай отклик шаблонным — он должен быть уникальным под конкретную задачу.

КРИТЕРИИ isMatch = false (не откликаться):
- Бюджет проекта ниже 10 000 рублей.
- Проект про вёрстку (HTML/CSS, landing page, сверстать, сверстай).
- Проект про WordPress (настройка, администрирование, шаблоны, плагины, WP).
- Проект про парсинг Avito, Юла, Циан, Дзен и других сервисов — парсинг данных с сайтов.
- Проект требует навыков, которых нет в моём стеке (мобильная разработка iOS/Android нативно, Unity, C++, PHP, Python и т.д.).
- Проект слишком мелкий или разовый (исправить одну кнопку, поменять цвет).

ДОПОЛНИТЕЛЬНО — Bitrix/1C-Bitrix:
- Если проект требует ТОЛЬКО Bitrix (настройка, администрирование, шаблоны Bitrix) — isMatch = false.
- Если проект использует Bitrix как платформу, но основная задача — интеграции, API, внешние сервисы, автоматизация или AI — isMatch = true, упомяни опыт интеграции с внешними системами.
`.trim();

function pickRandom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)] as T;
}

function buildCasesSection(profile: UserProfile): string {
  if (!profile.cases?.length) return "";
  const lines = profile.cases.map(
    (c, i) => `${i + 1}. ${c.description} [теги: ${c.tags.join(", ")}]`,
  );
  return `\nМОИ КЕЙСЫ (используй только их, не выдумывай новые):\n${lines.join("\n")}`;
}

export async function analyzeAndGenerateOffer(
  profile: UserProfile,
  project: KworkProject,
  noReviews = true,
): Promise<ProjectAnalysis> {
  const opening = pickRandom(OPENING_VARIANTS);
  const closing = pickRandom(CLOSING_VARIANTS);
  const flow = pickRandom(FLOW_VARIANTS);
  const trustPhrase = noReviews ? pickRandom(NO_REVIEWS_TRUST_VARIANTS) : null;

  const priceLimit = project.allow_higher_price
    ? (project.possible_price_limit ?? project.price)
    : project.price;
  const suggestedPrice = Math.min(Math.round(project.price * 1.1), priceLimit);

  const casesSection = buildCasesSection(profile);

  const userPrompt = `
Проанализируй проект и реши, стоит ли откликаться.

МОЙ ПРОФИЛЬ:
- Имя: ${profile.name}
- Специализация: ${profile.specialization}
- Опыт: ${profile.experienceYears} лет
- О себе: ${profile.bio}
- Портфолио: ${profile.portfolioDescription}

МОЙ СТЕК (сгруппирован по доменам):
- Frontend: Next.js, React, TypeScript, Tailwind CSS
- Backend/API: Node.js, Bun.js, tRPC, Hono.js
- Базы данных: PostgreSQL, ClickHouse
- AI/LLM: Vercel AI SDK, ChatGPT, LLM-интеграция, OpenRouter
- Инфраструктура: Docker, k3s, Vercel
- Автоматизация: trigger.dev, Inngest
${casesSection}

ПРОЕКТ:
- Название: ${project.title}
- Описание: ${project.description}
- Бюджет: ${project.price} руб.${project.allow_higher_price ? ` (готов платить до ${project.possible_price_limit ?? project.price} руб.)` : ""}
- Откликов уже: ${project.offers}
- Процент найма: ${project.user_hired_percent}%
${trustPhrase ? `\nNEW_PROFILE: true\nNO_REVIEWS_TRUST: "${trustPhrase}"` : ""}

ЗАДАЧА:
1. isMatch — подходит ли проект под мой стек (см. критерии в системном промпте)
2. reason — кратко почему да/нет (1-2 предложения)
3. suggestedDuration — реалистичный срок выполнения в днях (целое число, от 1 до 30). Если не подходит — верни 1.
4. proposalText — если подходит: напиши отклик. Начни с "${opening}", заверши фразой "${closing}". Подача: ${flow} Если не подходит — верни пустую строку.
`.trim();

  const result = await withModelFallback((model, modelId) =>
    generateText({
      model,
      system: AUTO_OFFER_SYSTEM_PROMPT,
      prompt: userPrompt,
      output: Output.object({ schema: analysisSchema }),
      temperature: 0.8,
      experimental_telemetry: {
        isEnabled: true,
        functionId: "analyze-and-generate-offer",
        metadata: { modelId },
      },
    }),
  );

  return {
    ...result.output,
    suggestedPrice,
    suggestedDuration: result.output.suggestedDuration,
  };
}
