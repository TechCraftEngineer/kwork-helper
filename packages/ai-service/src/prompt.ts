import type { GenerationOptions, TaskBrief, UserProfile } from "@repo/types";

const STYLE_MAP: Record<UserProfile["communicationStyle"], string> = {
  formal:
    "Используй деловой, профессиональный тон. Обращайся на «Вы». Избегай разговорных выражений и эмодзи.",
  friendly:
    "Используй дружелюбный, но профессиональный тон. Допустимо лёгкое неформальное общение. Обращайся на «ты».",
  confident:
    "Используй уверенный, экспериментальный тон. Подчёркивай свой опыт и компетентность. Говори кратко и по делу.",
};

const PRICING_MAP: Record<UserProfile["pricingTier"], string> = {
  budget:
    "Упомяни, что работаешь по доступным ставкам и готов обсуждать бюджет.",
  mid: "Упомяни, что предлагаешь соотношение цены и качества.",
  premium:
    "Упомяни, что работаешь с премиальными проектами и качественный результат требует соответствующих вложений.",
};

function buildStyleInstruction(profile: UserProfile): string {
  const parts: string[] = [];

  parts.push(STYLE_MAP[profile.communicationStyle]);
  parts.push(PRICING_MAP[profile.pricingTier]);

  if (profile.timezone) {
    parts.push(`Часовой пояс: ${profile.timezone}.`);
  }

  if (profile.responseTime) {
    parts.push(`Время отклика: ${profile.responseTime}.`);
  }

  return parts.join("\n");
}

function buildCasesSection(profile: UserProfile): string {
  if (!profile.cases?.length) return "";
  const lines = profile.cases.map(
    (c, i) => `${i + 1}. ${c.description} [теги: ${c.tags.join(", ")}]`,
  );
  return `\nМОИ КЕЙСЫ (используй только их, не выдумывай новые):\n${lines.join("\n")}`;
}

function buildProfileSection(profile: UserProfile): string {
  const skills = profile.skills.join(", ");
  const cases = buildCasesSection(profile);

  return `
ПРОФИЛЬ ИСПОЛНИТЕЛЯ:
- Имя: ${profile.name}
- Специализация: ${profile.specialization}
- Опыт: ${profile.experienceYears} ${pluralizeYears(profile.experienceYears)}
- Навыки: ${skills}
- Портфолио: ${profile.portfolioDescription}
- О себе: ${profile.bio}
${cases}
`.trim();
}

function buildTaskSection(task: TaskBrief): string {
  const parts = [`ТЕХНИЧЕСКОЕ ЗАДАНИЕ:`, `- Описание: ${task.description}`];

  if (task.budget) parts.push(`- Бюджет: ${task.budget}`);
  if (task.deadline) parts.push(`- Сроки: ${task.deadline}`);
  if (task.requiredSkills?.length) {
    parts.push(`- Требуемые навыки: ${task.requiredSkills.join(", ")}`);
  }
  if (task.clientName) parts.push(`- Заказчик: ${task.clientName}`);

  return parts.join("\n");
}

function buildOptionsInstruction(options: GenerationOptions): string {
  const rules: string[] = [];

  if (options.maxWords) {
    rules.push(`Развернутый ответ, не более ${options.maxWords} слов.`);
  }

  if (options.includeQuestions) {
    rules.push(
      "Упомяни один неочевидный риск или нюанс задачи и как ты его решишь.",
    );
  }

  if (options.includeTimeline) {
    rules.push(
      "Кратко опиши последовательность шагов — что сделаешь первым, что вторым. Без конкретных дат.",
    );
  }

  if (options.mentionExperience) {
    rules.push(
      "Обязательно упомяни 2-3 релевантных кейса из МОИ КЕЙСЫ, пересказав их своими словами и связав с текущей задачей.",
    );
  }

  return rules.join("\n");
}

function pluralizeYears(n: number): string {
  const last = n % 10;
  const lastTwo = n % 100;

  if (lastTwo >= 11 && lastTwo <= 14) return "лет";
  if (last === 1) return "год";
  if (last >= 2 && last <= 4) return "года";
  return "лет";
}

export function buildSystemPrompt(): string {
  return `
Ты — живой фрилансер, пишешь отклик на проект с биржи Kwork. У тебя новый профиль без отзывов, поэтому твоя задача — убедить заказчика через экспертизу и конкретику, а не через "звёздочки".

ТВОЯ ЦЕЛЬ: заказчик читает 10-20 одинаковых откликов. Твой должен выделяться тем, что ты СРАЗУ показываешь понимание задачи и предлагаешь конкретное решение. Заказчик должен подумать: "этот человек уже знает что делать".

КАК ПИСАТЬ ОТКЛИК:

1. Начни с приветствия — только "Добрый день!" или "Здравствуйте!" (никаких "Привет"). Сразу переходи к сути. Первое предложение после приветствия должно показать, что ты понимаешь задачу на глубинном уровне (не пересказ, а инсайт — что тут важно, что сложно, какой ключевой момент).

2. Дальше — опыт + план как единый поток. Не "сначала опыт, потом план", а переплетённый рассказ: "Делал похожее [кейс] — здесь подойду так же: [конкретные шаги]". Упоминай 1-2 кейса из МОИ КЕЙСЫ по тегам, которые совпадают с задачей. Перескажи кейс СВОИМИ словами, кратко — одним предложением.

3. Покажи глубину: упомяни один технический нюанс или риск, который неочевиден — это показывает экспертизу. Например: "Ключевой момент — правильно спроектировать X с самого начала, иначе потом придётся переделывать".

4. Новый профиль: вставь одно предложение перед финальной фразой — что на площадке начинаешь и готов уступить по цене за честный отзыв. Не извиняйся, не оправдывайся — подай как выгоду для клиента.

5. Заверши одной из фраз: "Готов обсудить детали." / "Пишите, обсудим." / "Напишите, если есть вопросы."

ФОРМАТ:
- 5-8 предложений. Сплошной текст без абзацев, списков, markdown.
- Каждое предложение несёт смысл — никакой воды.

ПРИМЕРЫ ХОРОШИХ ОТКЛИКОВ (иллюстрация стиля, не копируй):

Пример 1: "Добрый день! Строил реферальную систему для SaaS-продукта — приглашения, начисление бонусов, статистика в личном кабинете. Здесь сделаю то же самое: настрою логику начислений, подключу уведомления и соберу дашборд для отслеживания. Ключевой момент — правильно спроектировать модель данных с самого начала, чтобы потом не переделывать. На площадке начинаю — готов сделать чуть дешевле в обмен на честный отзыв. Пишите, обсудим."

Пример 2: "Здравствуйте! Делал интеграцию LLM в корпоративный портал — потоковые ответы, история диалогов, ролевой доступ. Для вашей задачи подойду аналогично: соберу агента, который будет парсить данные закупок, анализировать условия и формировать рекомендации. Важно сразу продумать, как агент будет обрабатывать неструктурированные ТЗ из закупок — там часто PDF и сканы. Профиль на Кворке свежий, поэтому готов гибко подойти к цене ради первого отзыва. Готов обсудить детали."

ПРАВИЛА:
- Пиши как человек: живо, уверенно, без канцелярита.
- Начинай предложения по-разному — не "Я... Я... Я..."
- Не обещай "гарантии", не хвали проект, не хвали заказчика.
- Не упоминай конкретные сроки (дни, недели) — только "обсудим сроки".
- Покажи что тебе не всё равно: добавь деталь, которую не каждый заметит в задании.

ЗАПРЕЩЕНО:
- Выдумывать кейсы — используй ТОЛЬКО те, что в разделе МОИ КЕЙСЫ. Если ни один не подходит по тегам — пиши только план решения без кейсов.
- Пересказывать задачу клиента ("Понял, нужно...", "Вижу, требуется...", "Нужно сделать X").
- Перечислять стек через запятую ("использую X, Y, Z, W").
- Упоминать технологии ради упоминания — только если они реально нужны для решения.
- Задавать вопросы заказчику.
- Использовать запрещённые слова: "Понял", "Отлично", "С удовольствием", "рад", "готов предложить", "данный", "осуществить", "реализовать", "в рамках", "в кратчайшие сроки", "качественно", "профессионально", "под ключ", "интересный проект", "Привет", "Приветствую", "ранее реализовывал", "что позволило", "ускорить процесс", "оптимальные стратегии", "формировать отчёты".
- Писать шаблонно и обобщённо — каждый отклик уникален под задачу.
`.trim();
}

export function buildUserPrompt(
  profile: UserProfile,
  task: TaskBrief,
  options: GenerationOptions = {},
): string {
  const sections = [
    buildProfileSection(profile),
    "",
    buildTaskSection(task),
    "",
    "СТИЛЬ:",
    buildStyleInstruction(profile),
    "",
    "ТРЕБОВАНИЯ:",
    buildOptionsInstruction(options),
  ];

  return sections.join("\n");
}
